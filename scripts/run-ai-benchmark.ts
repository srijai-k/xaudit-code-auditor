// Runs XAUDIT over real, unedited AI-tool output in tests/ai-benchmark/
// and writes docs/ai-benchmark-report.md. Run with: npm run bench:ai
//
// Methodology discipline, same as the other benchmarks: this script only
// RUNS and REPORTS. It never decides what's a real problem. That comes from
// tests/ai-benchmark/labels.json, filled in by a person who read the code.
// A response with no label is listed but not scored, and the report says
// so at the top - it never presents unlabeled findings as "caught".
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { analyze } from "../src/lib/analysis/analyze";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const benchDir = path.join(root, "tests", "ai-benchmark");
const responsesDir = path.join(benchDir, "responses");
const reportPath = path.join(root, "docs", "ai-benchmark-report.md");

interface Label {
    real?: string[];
    notReal?: string[];
    missed?: string[];
}

const prompts: { id: string; prompt: string }[] = JSON.parse(readFileSync(path.join(benchDir, "prompts.json"), "utf8"));
const labelsRaw: Record<string, Label | string> = JSON.parse(readFileSync(path.join(benchDir, "labels.json"), "utf8"));
const labels = Object.fromEntries(Object.entries(labelsRaw).filter(([k]) => !k.startsWith("_"))) as Record<string, Label>;

const CODE_EXT = /\.(js|jsx|ts|tsx|mjs|cjs|html|htm|json)$/i;
const modeFor = (file: string) => (/\.html?$/i.test(file) ? "html" : /\.json$/i.test(file) ? "package-json" : "script") as "html" | "script" | "package-json";

const tools = existsSync(responsesDir)
    ? readdirSync(responsesDir).filter((d) => statSync(path.join(responsesDir, d)).isDirectory()).sort()
    : [];

interface Row {
    key: string;
    tool: string;
    promptId: string;
    status: string;
    findings: string[];
    label?: Label;
}

const rows: Row[] = [];
for (const tool of tools) {
    for (const file of readdirSync(path.join(responsesDir, tool)).filter((f) => CODE_EXT.test(f)).sort()) {
        const code = readFileSync(path.join(responsesDir, tool, file), "utf8");
        const result = analyze(code, modeFor(file));
        const key = `${tool}/${file}`;
        rows.push({
            key,
            tool,
            promptId: file.replace(/(--.*)?\.[^.]+$/, ""),
            status: result.status === "ok" ? "ok" : `${result.status}: ${result.error ?? ""}`,
            findings: result.findings.map((f) => f.ruleId),
            label: labels[key],
        });
    }
}

const labelled = rows.filter((r) => r.label);
let caught = 0, falseAlarms = 0, missed = 0, unreviewed = 0;
for (const r of labelled) {
    const real = new Set(r.label!.real ?? []);
    const notReal = new Set(r.label!.notReal ?? []);
    caught += r.findings.filter((f) => real.has(f)).length;
    falseAlarms += r.findings.filter((f) => notReal.has(f)).length;
    unreviewed += r.findings.filter((f) => !real.has(f) && !notReal.has(f)).length;
    missed += (r.label!.missed ?? []).length;
}

const esc = (s: string) => s.replace(/\|/g, "\\|");
let md = `# XAUDIT on real AI-tool output\n\n`;
md += `Generated by \`npm run bench:ai\` (\`scripts/run-ai-benchmark.ts\`) from \`tests/ai-benchmark/\`. Don't hand-edit this file.\n\n`;
md += `> **What this is.** Code written by AI tools in answer to the ${prompts.length} everyday prompts in \`tests/ai-benchmark/prompts.json\`, pasted in unedited, then checked by XAUDIT. Whether a finding is a real problem is decided by a person reading the code (\`labels.json\`), never by this script. Responses that haven't been labelled yet are listed but not counted.\n\n`;

if (rows.length === 0) {
    md += `## No responses collected yet\n\nNothing has been added to \`tests/ai-benchmark/responses/\` yet, so there are no results. See [\`tests/ai-benchmark/README.md\`](../tests/ai-benchmark/README.md) for how to collect them.\n`;
} else {
    md += `## Summary\n\n`;
    md += `| Responses | Labelled | Real problems XAUDIT caught | False alarms | Real problems XAUDIT missed | Findings not yet reviewed |\n|---|---|---|---|---|---|\n`;
    md += `| ${rows.length} | ${labelled.length} | ${caught} | ${falseAlarms} | ${missed} | ${unreviewed} |\n\n`;
    if (labelled.length < rows.length) md += `${rows.length - labelled.length} response(s) aren't labelled yet, so the counts above only cover ${labelled.length}.\n\n`;
    md += `## By tool\n\n| Tool | Responses | Labelled | XAUDIT findings |\n|---|---|---|---|\n`;
    for (const tool of tools) {
        const t = rows.filter((r) => r.tool === tool);
        if (t.length) md += `| ${tool} | ${t.length} | ${t.filter((r) => r.label).length} | ${t.reduce((n, r) => n + r.findings.length, 0)} |\n`;
    }
    md += `\n## Every response\n\n| Response | Prompt | XAUDIT found | Human verdict |\n|---|---|---|---|\n`;
    for (const r of rows) {
        const prompt = prompts.find((p) => p.id === r.promptId)?.prompt ?? "(unknown prompt id)";
        const found = r.status !== "ok" ? `_${esc(r.status.slice(0, 80))}_` : r.findings.length ? r.findings.map((f) => `\`${f}\``).join(", ") : "nothing";
        const verdict = !r.label
            ? "_not labelled yet_"
            : [
                  r.label.real?.length ? `real: ${r.label.real.join(", ")}` : "",
                  r.label.notReal?.length ? `false alarm: ${r.label.notReal.join(", ")}` : "",
                  r.label.missed?.length ? `missed: ${r.label.missed.map(esc).join("; ")}` : "",
              ].filter(Boolean).join("<br>") || "no problems found by the reviewer";
        md += `| \`${r.key}\` | ${esc(prompt)} | ${found} | ${verdict} |\n`;
    }
}

writeFileSync(reportPath, md);
console.log(`Wrote docs/ai-benchmark-report.md: ${rows.length} responses, ${labelled.length} labelled${rows.length ? `, caught ${caught}, false alarms ${falseAlarms}, missed ${missed}` : ""}`);
