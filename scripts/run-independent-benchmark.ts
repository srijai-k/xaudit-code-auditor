// Scores tests/independent-benchmark/samples/* against ground truth that
// was written BEFORE this script was ever run against the live engine (see
// manifest.json's per-file "reasoning" fields) — a separate, differently-
// biased corpus from tests/fixtures/, not a second copy of it. Run with:
// npm run bench:independent
//
// Methodology discipline this script exists to enforce: this file only
// SCORES and REPORTS. It never adjusts ground truth to match what the
// engine actually produced. A mismatch is written to the report as a
// mismatch, full stop — see docs/independent-benchmark-report.md's
// "Mismatches found" section for what happened the first time this ran.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { analyze } from "../src/lib/analysis/analyze";

const root = path.dirname(fileURLToPath(import.meta.url));
const benchDir = path.join(root, "..", "tests", "independent-benchmark");
const manifest = JSON.parse(readFileSync(path.join(benchDir, "manifest.json"), "utf8"));

interface ExpectedFinding {
    ruleId: string;
    severity: string;
}

interface FileEntry {
    file: string;
    expectedFindings: ExpectedFinding[];
    reasoning: string;
}

interface FileResult {
    file: string;
    reasoning: string;
    tp: ExpectedFinding[];
    fp: ExpectedFinding[];
    fn: ExpectedFinding[];
}

function pairKey(p: { ruleId: string; severity: string }): string {
    return `${p.ruleId}::${p.severity}`;
}

const results: FileResult[] = [];

for (const entry of manifest.files as FileEntry[]) {
    const code = readFileSync(path.join(benchDir, "samples", entry.file), "utf8");
    const analysisResult = analyze(code, "script");
    const actual = analysisResult.findings.map((f) => ({ ruleId: f.ruleId, severity: f.severity }));

    // Multiset match: consume each expected finding against an available
    // actual one with the same ruleId+severity. Whatever's left over on
    // either side is a mismatch.
    const remainingActual = [...actual];
    const tp: ExpectedFinding[] = [];
    const fn: ExpectedFinding[] = [];
    for (const exp of entry.expectedFindings) {
        const idx = remainingActual.findIndex((a) => pairKey(a) === pairKey(exp));
        if (idx >= 0) {
            tp.push(exp);
            remainingActual.splice(idx, 1);
        } else {
            fn.push(exp);
        }
    }
    const fp: ExpectedFinding[] = remainingActual;

    results.push({ file: entry.file, reasoning: entry.reasoning, tp, fp, fn });
}

const totalTp = results.reduce((s, r) => s + r.tp.length, 0);
const totalFp = results.reduce((s, r) => s + r.fp.length, 0);
const totalFn = results.reduce((s, r) => s + r.fn.length, 0);
const precision = totalTp + totalFp === 0 ? 1 : totalTp / (totalTp + totalFp);
const recall = totalTp + totalFn === 0 ? 1 : totalTp / (totalTp + totalFn);
const f1 = precision + recall === 0 ? 0 : (2 * precision * recall) / (precision + recall);

let md = `# XAUDIT Independent Benchmark Report\n\n`;
md += `> **What this is, and how it's different from \`docs/benchmark-report.md\`.** That report scores the exact corpus (\`tests/fixtures/\`) that was written alongside the rules, one small file per specific pattern, iterated on until each rule's own tests passed — a regression signal, explicitly disclosed there as not a real-world accuracy measurement. This report scores a **separate** corpus (\`tests/independent-benchmark/samples/\`): larger, more realistic, multi-concern files — a small Express router, a React dashboard widget, a Node backup script, a config module — with ground truth written down in \`manifest.json\` by manual security review *before* this script was ever run, and never adjusted afterward to match what the engine produced. That is a real, meaningful difference in independence. It is still not a fully external, third-party benchmark — the same person wrote the rules and this corpus — so treat this as a second, differently-biased data point, not proof of real-world accuracy either.\n\n`;
md += `Generated by \`npm run bench:independent\` (\`scripts/run-independent-benchmark.ts\`) against \`tests/independent-benchmark/manifest.json\` and the live \`analyze()\` engine.\n\n`;
md += `Generated: ${new Date().toISOString()}\n\n`;
md += `## Overall\n\n`;
md += `| Files | TP | FP | FN | Precision | Recall | F1 |\n|---|---|---|---|---|---|---|\n`;
md += `| ${results.length} | ${totalTp} | ${totalFp} | ${totalFn} | ${precision.toFixed(2)} | ${recall.toFixed(2)} | ${f1.toFixed(2)} |\n\n`;

md += `## Per-file detail\n\n`;
md += `| File | Expected | TP | FP | FN |\n|---|---|---|---|---|\n`;
for (const r of results) {
    const expectedStr = r.tp.length + r.fn.length === 0 ? "(none)" : [...r.tp, ...r.fn].map((e) => `${e.ruleId}/${e.severity}`).join(", ");
    md += `| \`${r.file}\` | ${expectedStr} | ${r.tp.length} | ${r.fp.length} | ${r.fn.length} |\n`;
}

md += `\n## Mismatches found\n\n`;
const withMismatches = results.filter((r) => r.fp.length > 0 || r.fn.length > 0);
md += withMismatches.length === 0
    ? "None in this run — every file's actual findings matched the ground truth recorded in `manifest.json` before this script was run.\n"
    : withMismatches.map((r) => {
          let s = `### \`${r.file}\`\n\n${r.reasoning}\n\n`;
          if (r.fp.length > 0) s += r.fp.map((f) => `- **Unexpected finding (FP):** \`${f.ruleId}\` (${f.severity})\n`).join("");
          if (r.fn.length > 0) s += r.fn.map((f) => `- **Missed finding (FN):** \`${f.ruleId}\` (${f.severity})\n`).join("");
          return s;
      }).join("\n");

md += `\n## Ground truth, file by file\n\n`;
for (const entry of manifest.files as FileEntry[]) {
    md += `- **\`${entry.file}\`**: ${entry.reasoning}\n`;
}

md += `\n## Methodology notes\n\n`;
md += `- ${results.length} realistic, multi-concern files, independently authored (not copies or trivial rewordings of \`tests/fixtures/\` cases), covering all five rule groups plus deliberate noise-floor checks on ordinary, larger, non-trivial "nothing wrong here" code.\n`;
md += `- Ground truth was written into \`manifest.json\` from manual security review of each file, before this scoring script was ever executed against the engine.\n`;
md += `- When this benchmark surfaced a real, previously-undocumented gap during its own construction, the fix and the honest before/after are logged in \`docs/model-improvements.md\`, not silently folded in here.\n`;
md += `- This is still not a third-party or externally-sourced dataset. Treat it as a second, differently-biased check, not a claim of real-world accuracy.\n`;
md += `- Re-run with \`npm run bench:independent\` any time a rule changes.\n`;

writeFileSync(path.join(root, "..", "docs", "independent-benchmark-report.md"), md, "utf8");
console.log(`Wrote docs/independent-benchmark-report.md — ${results.length} files, TP=${totalTp} FP=${totalFp} FN=${totalFn}, precision ${precision.toFixed(2)}, recall ${recall.toFixed(2)}, F1 ${f1.toFixed(2)}`);
