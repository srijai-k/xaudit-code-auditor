// Computes real precision/recall/F1 from tests/expected-results.json against
// the live analyze() function, and writes docs/benchmark-report.md.
// Run with: npm run bench
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { analyze } from "../src/lib/analysis/analyze";

const root = path.dirname(fileURLToPath(import.meta.url));
const testsDir = path.join(root, "..", "tests");
const manifest = JSON.parse(readFileSync(path.join(testsDir, "expected-results.json"), "utf8"));

interface Row {
    id: string;
    group: string;
    bucket: string;
    outcome: "TP" | "FP" | "FN" | "TN";
    findingRuleIds: string[];
    note: string;
}

const rows: Row[] = [];

for (const [id, exp] of Object.entries<any>(manifest)) {
    const code = readFileSync(path.join(testsDir, exp.path), "utf8");
    const result = analyze(code, exp.mode ?? "script");
    const findingRuleIds = result.findings.map((f: any) => f.ruleId);

    const shouldFlag = exp.expectRuleIds.length > 0;
    const didFlag = exp.expectRuleIds.length > 0
        ? exp.expectRuleIds.some((r: string) => findingRuleIds.includes(r))
        : findingRuleIds.length > 0 && exp.forbidSeverity
            ? result.findings.some((f: any) => severityRank(f.severity) >= severityRank(exp.forbidSeverity))
            : false;

    let outcome: Row["outcome"];
    if (shouldFlag && didFlag) outcome = "TP";
    else if (shouldFlag && !didFlag) outcome = "FN";
    else if (!shouldFlag && didFlag) outcome = "FP";
    else outcome = "TN";

    rows.push({ id, group: exp.group, bucket: exp.bucket, outcome, findingRuleIds, note: exp.note });
}

function severityRank(s: string): number {
    return { info: 0, low: 1, medium: 2, high: 3, critical: 4 }[s] ?? 0;
}

function metricsFor(rows: Row[]) {
    const tp = rows.filter((r) => r.outcome === "TP").length;
    const fp = rows.filter((r) => r.outcome === "FP").length;
    const fn = rows.filter((r) => r.outcome === "FN").length;
    const tn = rows.filter((r) => r.outcome === "TN").length;
    const precision = tp + fp === 0 ? (tp === 0 ? 1 : 0) : tp / (tp + fp);
    const recall = tp + fn === 0 ? (tp === 0 ? 1 : 0) : tp / (tp + fn);
    const f1 = precision + recall === 0 ? 0 : (2 * precision * recall) / (precision + recall);
    return { tp, fp, fn, tn, precision, recall, f1 };
}

const groups = [...new Set(rows.map((r) => r.group))];

let md = `# XAUDIT Benchmark Report\n\n`;
md += `> **What this is, and is not.** This report is computed against the project's own regression corpus (\`tests/fixtures/\`), which was written alongside the rules being tested. A precision/recall of 1.00 here means "the engine still behaves the way its own test suite says it should" — it is a regression signal, not an independent measurement of real-world accuracy. It says nothing about code this corpus doesn't cover. Do not cite this report as evidence of general detection accuracy, "zero false positives" in the wild, or coverage of any vulnerability class beyond the five rule groups implemented (see README "Current supported checks"). Real-world code will produce both false positives and false negatives this corpus does not exercise.\n\n`;
md += `Generated by \`npm run bench\` (\`scripts/run-benchmark.ts\`) against \`tests/expected-results.json\` and the live \`analyze()\` engine. This is not a curated or cherry-picked sample in the sense of hiding failures — it is the exact corpus committed under \`tests/fixtures/\`, the same one the CI-failing test suite in \`tests/\` runs against, including cases deliberately designed to demonstrate known blind spots (see below).\n\n`;
md += `Generated: ${new Date().toISOString()}\n\n`;
md += `## Overall\n\n`;
const overall = metricsFor(rows);
md += `| Cases | TP | FP | FN | TN | Precision | Recall | F1 |\n|---|---|---|---|---|---|---|---|\n`;
md += `| ${rows.length} | ${overall.tp} | ${overall.fp} | ${overall.fn} | ${overall.tn} | ${overall.precision.toFixed(2)} | ${overall.recall.toFixed(2)} | ${overall.f1.toFixed(2)} |\n\n`;

md += `## By rule group\n\n`;
md += `| Group | Cases | TP | FP | FN | TN | Precision | Recall | F1 |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const g of groups) {
    const groupRows = rows.filter((r) => r.group === g);
    const m = metricsFor(groupRows);
    md += `| ${g} | ${groupRows.length} | ${m.tp} | ${m.fp} | ${m.fn} | ${m.tn} | ${m.precision.toFixed(2)} | ${m.recall.toFixed(2)} | ${m.f1.toFixed(2)} |\n`;
}

md += `\n## Case-by-case detail\n\n| ID | Group | Bucket | Outcome | Findings raised | Note |\n|---|---|---|---|---|---|\n`;
for (const r of rows) {
    md += `| ${r.id} | ${r.group} | ${r.bucket} | ${r.outcome} | ${r.findingRuleIds.join(", ") || "(none)"} | ${r.note} |\n`;
}

const failing = rows.filter((r) => r.outcome === "FP" || r.outcome === "FN");
md += `\n## Failing cases in this run\n\n`;
md += failing.length === 0
    ? "None — every case in the corpus matches its documented expectation.\n"
    : failing.map((r) => `- **${r.outcome}** \`${r.id}\` (${r.group}): ${r.note}\n`).join("");

const documentedLimitations = rows.filter((r) => r.bucket === "edge-cases" || /KNOWN|known false negative|documented on purpose/i.test(r.note));
md += `\n## Documented blind spots (intentionally included, not failures)\n\n`;
md += `These cases pass their test (the engine does exactly what it says it does) but exist specifically to keep a real limitation visible instead of only testing favorable cases:\n\n`;
md += documentedLimitations.length === 0
    ? "None currently in the corpus.\n"
    : documentedLimitations.map((r) => `- \`${r.id}\` (${r.group}, outcome ${r.outcome}): ${r.note}\n`).join("");

md += `\n## Methodology notes\n\n- This corpus is intentionally narrow (54 cases across the specific rule groups implemented). It is not a general-purpose vulnerability benchmark and must not be cited as one.\n- "TN" (true negative) rows are safe fixtures where no finding at/above the case's \`forbidSeverity\` threshold appeared, as intended.\n- Documented false negatives (e.g. \`sqli-concat-via-variable-not-caught\`) are included in the corpus on purpose, to keep the engine's real limitations visible in this report rather than hidden by only testing cases it handles well.\n- Re-run with \`npm run bench\` any time a rule changes; this file should be regenerated, not hand-edited.\n`;

writeFileSync(path.join(root, "..", "docs", "benchmark-report.md"), md, "utf8");
console.log(`Wrote docs/benchmark-report.md — overall precision ${overall.precision.toFixed(2)}, recall ${overall.recall.toFixed(2)}, F1 ${overall.f1.toFixed(2)}`);
